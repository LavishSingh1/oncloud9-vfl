#!/usr/bin/env sh
# Pin the Docker base image by digest and lock every Python dependency to an exact version.
#
#   scripts/pin_deps.sh                       # uses python:3.11-slim-bookworm
#   BASE_TAG=python:3.11-slim-bookworm scripts/pin_deps.sh
#
# Writes:
#   docker/Dockerfile   FROM line -> <BASE_TAG>@sha256:<digest of the tag right now>
#   requirements.lock   `pip freeze` of a clean install of requirements.txt (+ CPU torch) inside that
#                       exact base image: every package, transitive ones included, as name==version.
# Commit both files. Re-run deliberately (e.g. to pick up security fixes), never implicitly.
set -eu
cd "$(dirname "$0")/.."

BASE_TAG="${BASE_TAG:-python:3.11-slim-bookworm}"
TORCH_INDEX="https://download.pytorch.org/whl/cpu"

echo "pulling $BASE_TAG ..."
docker pull -q "$BASE_TAG" >/dev/null
# RepoDigests holds the manifest-list digest for the tag that was pulled (multi-arch safe).
PINNED="$(docker image inspect --format '{{range .RepoDigests}}{{println .}}{{end}}' "$BASE_TAG" \
          | grep -m1 "@sha256:")"
DIGEST="${PINNED#*@}"
case "$DIGEST" in sha256:????????????????????????????????????????????????????????????????) ;;
  *) echo "could not resolve a digest for $BASE_TAG (got: '$PINNED')" >&2; exit 1 ;; esac
REF="$BASE_TAG@$DIGEST"
echo "base image: $REF"

# Replace the first FROM line only.
awk -v ref="$REF" '!done && /^FROM /{print "FROM " ref; done=1; next} {print}' docker/Dockerfile \
  > docker/Dockerfile.tmp && mv docker/Dockerfile.tmp docker/Dockerfile

echo "resolving exact dependency versions inside $REF ..."
FROZEN="$(docker run --rm --user 0 -v "$PWD/requirements.txt:/tmp/requirements.txt:ro" \
  --entrypoint sh "$REF" -c "
    set -e
    export PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1
    pip install -q torch --index-url $TORCH_INDEX
    pip install -q -r /tmp/requirements.txt
    pip check >&2
    pip freeze")"

{
  echo "# Exact versions of every Python package in the Docker image (transitive dependencies included)."
  echo "# Generated by scripts/pin_deps.sh in $REF"
  echo "# Used as a pip constraints file:  pip install -r requirements.txt -c requirements.lock"
  echo "# (torch: install from $TORCH_INDEX first, as the Dockerfile does)."
  echo "$FROZEN" | grep -E '^[A-Za-z0-9_.-]+==' | LC_ALL=C sort -f
} > requirements.lock

echo "wrote docker/Dockerfile (FROM $REF) and requirements.lock ($(grep -c '==' requirements.lock) packages)"
echo "next: docker compose -f docker/docker-compose.yml build && git add docker/Dockerfile requirements.lock"
